#!/usr/bin/env python3
"""Generate the Unicode codepoint ranges CPython's `str.isalnum()` matches.

`plugins/shell.py::ShellPlugin.execute`'s own bare-command check
(`command.replace("-", "").replace("_", "").isalnum()`) uses CPython's own
`str.isalnum()`: true for a character whose `str.isalpha()`, `str.isdecimal()`,
`str.isdigit()`, or `str.isnumeric()` is true (Unicode category Lu/Ll/Lt/Lm/Lo
for `isalpha`, Nd for `isdecimal`/most of `isdigit`, plus the few extra
digit-valued characters `isdigit()` also accepts, plus Nl/No for `isnumeric`).

Rust's own `char::is_alphanumeric()` is *not* the same predicate: it follows
Unicode's derived `Alphabetic`/`Numeric` properties, which are strict
supersets of CPython's category-based definition here (confirmed directly:
15,559 codepoints in Unicode 14.0 -- e.g. U+0345 COMBINING GREEK YPOGEGRAMMENI,
a combining mark with the derived `Other_Alphabetic` property but category Mn
-- are `true` under Rust's `is_alphanumeric()` and `false` under CPython's
`isalnum()`; the reverse never happens). Rather than depend on a Unicode-
category crate pinned to whatever Unicode version it last shipped with (the
same parity risk `generate_unicode_printable_ranges.py`'s own docstring
names), this script reads the answer directly from the interpreter
generating electricity's golden corpus, and writes it into the crate as
generated, checked-in Rust source.

Must be run with the same Python version/Unicode Character Database version
used to generate the golden corpus (see generate_value_corpus.py) -- CI and
the lane venv both pin Python 3.11.

Usage: python3 generate_unicode_alnum_ranges.py [--check]
Writes: crates/electricity-tools/src/generated/unicode_alnum_ranges.rs
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUTPUT = (
    Path(__file__).resolve().parent.parent
    / "crates"
    / "electricity-tools"
    / "src"
    / "generated"
    / "unicode_alnum_ranges.rs"
)


def alnum_ranges() -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    start: int | None = None
    for cp in range(0x110000):
        is_alnum = chr(cp).isalnum()
        if is_alnum and start is None:
            start = cp
        elif not is_alnum and start is not None:
            ranges.append((start, cp - 1))
            start = None
    if start is not None:
        ranges.append((start, 0x10FFFF))
    return ranges


def render(ranges: list[tuple[int, int]]) -> str:
    lines = [f"    (0x{lo:X}, 0x{hi:X})," for lo, hi in ranges]
    body = "\n".join(lines)
    return f"""\
//! Generated by `electricity/scripts/generate_unicode_alnum_ranges.py`.
//! Do not hand-edit; re-run the script instead.
//!
//! Inclusive `(low, high)` codepoint ranges where CPython's `str.isalnum()`
//! is `True`, generated against the Unicode Character Database version the
//! script's Python interpreter ships.
//!
//! Unicode Character Database version: {unicodedata.unidata_version}.

pub(crate) const ALNUM_RANGES: &[(u32, u32)] = &[
{body}
];
"""


def main() -> int:
    ranges = alnum_ranges()
    text = render(ranges)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is stale; run without --check to regenerate", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT} ({len(ranges)} ranges)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
