#!/usr/bin/env python3
"""Generate the set of codec names CPython's own `codecs.lookup` accepts
(`encodings.aliases.aliases`'s keys and values, plus every module name the
`encodings` package itself ships), normalized the way `_PyCodec_Lookup`'s
own C-level `normalizestring` does: lowercase, then every run of characters
that isn't `[a-z0-9.]` collapsed to a single `_`, trimmed from both ends.

`electricity-tools`'s `fs`/`hash` plugins implement only three of these
codecs (`utf-8`/`ascii`/`latin-1`, in `fs.rs::resolve_codec`) -- a
documented narrowing, #448 decision 8. For a name outside that set, this
table lets the Rust side tell apart two different failures: a name CPython
itself would also reject (`LookupError: unknown encoding: x`, this
preview's and `cof run`'s own text) from a name CPython accepts but this
preview doesn't implement (refused upfront, before anything touches the
filesystem, with the preview marker -- #460's lane D1 fix pass, "R2").

Must be run with the same Python version as the rest of the generated
corpus (3.11) -- the `encodings` package's own module list is a stdlib
implementation detail that can change between versions.

Usage: python3 generate_codec_names.py [--check]
Writes: crates/electricity-tools/src/generated/python_codec_names.rs
"""

from __future__ import annotations

import encodings
import encodings.aliases
import pkgutil
import sys
from pathlib import Path

OUTPUT = (
    Path(__file__).resolve().parent.parent
    / "crates"
    / "electricity-tools"
    / "src"
    / "generated"
    / "python_codec_names.rs"
)


def normalize(name: str) -> str:
    out: list[str] = []
    pending_sep = False
    for ch in name:
        lower = ch.lower()
        if lower.isascii() and (lower.isalnum() or lower == "."):
            if pending_sep and out:
                out.append("_")
            out.append(lower)
            pending_sep = False
        else:
            pending_sep = True
    return "".join(out)


def python_codec_names() -> list[str]:
    names: set[str] = set()
    for alias, canonical in encodings.aliases.aliases.items():
        names.add(normalize(alias))
        names.add(normalize(canonical))
    for _, module_name, _ in pkgutil.iter_modules(encodings.__path__):
        if module_name in ("aliases", "__init__"):
            continue
        names.add(normalize(module_name))
    return sorted(names)


def render(names: list[str]) -> str:
    lines = [f'    "{name}",' for name in names]
    body = "\n".join(lines)
    return f"""\
//! Generated by `electricity/scripts/generate_codec_names.py`.
//! Do not hand-edit; re-run the script instead.
//!
//! Every codec name/alias `codecs.lookup` (CPython 3.11) accepts,
//! normalized (lowercase, non-`[a-z0-9.]` runs collapsed to `_`). Used
//! by `fs.rs::classify_encoding` to tell a name CPython itself would
//! reject from one it accepts but this preview doesn't implement.

pub(crate) const PYTHON_CODEC_NAMES: &[&str] = &[
{body}
];
"""


def main() -> int:
    names = python_codec_names()
    text = render(names)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is stale; run without --check to regenerate", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT} ({len(names)} names)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
