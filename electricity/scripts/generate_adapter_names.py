#!/usr/bin/env python3
"""Copy Circuitry's adapter registry's name list into electricity-vm.

``adapters/factory.py::build_adapter``'s own "Unknown adapter: ... Supported
adapters: ..." text lists Python's *full* registry (every provider name in
``ADAPTER_REGISTRY``, sorted), not just the handful electricity itself can
build (PR #454 -- `AdapterRegistry::supported_names`
only ever lists the registry's own registered builders, empty for M1-A).
electricity-vm's own builder (``adapter.rs::AdapterRegistry::build``) needs
that exact list to word its own unknown-adapter message the same way, even
for a provider name no electricity lane has implemented yet -- the message
is only ever the reason a document-level ``adapter:``/`prompt` effect is
refused, never a dispatch decision, so it must speak to "every provider
Circuitry itself knows", not "every provider electricity knows".

Usage: python3 generate_adapter_names.py [--check]
"""

from __future__ import annotations

import sys
from pathlib import Path

from circuitry.adapters.factory import ADAPTER_REGISTRY

OUTPUT = (
    Path(__file__).resolve().parent.parent
    / "crates"
    / "electricity-vm"
    / "src"
    / "adapter_names.rs"
)

_HEADER = """\
//! @generated by `electricity/scripts/generate_adapter_names.py --check`.
//! Do not edit by hand -- it copies `adapters/factory.py::ADAPTER_REGISTRY`'s
//! own key set, sorted, into this crate so `adapter::AdapterRegistry::build`'s
//! own unknown-adapter message lists Python's full registry (PR #454).
"""


def render() -> str:
    names = sorted(ADAPTER_REGISTRY.keys())
    lines = [_HEADER, "pub const ADAPTER_NAMES: &[&str] = &["]
    lines.extend(f'    "{name}",' for name in names)
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    data = render().encode("utf-8")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_bytes() if OUTPUT.exists() else b""
        if current != data:
            print(f"{OUTPUT} is stale; run without --check to regenerate", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_bytes(data)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
