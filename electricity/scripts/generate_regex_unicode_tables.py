#!/usr/bin/env python3
"""Generate the Unicode codepoint ranges the Python-`re` translation
layer (`electricity-pyre::translate`, shared by the `regex` tool and
electricity-schema's JSON Schema `pattern` keyword) needs for Python `re`'s
`\\w`, `\\s` and `\\d` classes (#479, #448 lane D2), read directly from
CPython's own definitions rather than guessed at or copied from Rust's
own (different) Unicode tables:

- `\\w` is `str.isalnum() or c == "_"` (`sre_compile.py`'s own
  `CATEGORY_UNI_WORD` definition);
- `\\s` is `str.isspace()`;
- `\\d` is Unicode category `Nd` (decimal digit).

`\\b`/`\\B` follow directly from `\\w` at the translator, so they need no
table of their own.

Must be run with the same Python version/Unicode Character Database
version used to generate the other regex corpora -- CI and the lane
venv both pin Python 3.11 (Unicode 14.0).

Usage: python3 generate_regex_unicode_tables.py [--check]
Writes: crates/electricity-pyre/src/regex_unicode.rs
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

OUTPUT = (
    Path(__file__).resolve().parent.parent
    / "crates"
    / "electricity-pyre"
    / "src"
    / "regex_unicode.rs"
)


def ranges_where(predicate) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    start: int | None = None
    for cp in range(0x110000):
        hit = predicate(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            ranges.append((start, cp - 1))
            start = None
    if start is not None:
        ranges.append((start, 0x10FFFF))
    return ranges


def render(word: list, space: list, digit: list) -> str:
    def body(ranges: list[tuple[int, int]]) -> str:
        return "\n".join(f"    (0x{lo:X}, 0x{hi:X})," for lo, hi in ranges)

    return f"""\
//! Generated by `electricity/scripts/generate_regex_unicode_tables.py`.
//! Do not hand-edit; re-run the script instead.
//!
//! Inclusive `(low, high)` codepoint ranges for Python `re`'s `\\w`
//! (`str.isalnum()` plus `_`), `\\s` (`str.isspace()`) and `\\d`
//! (Unicode category `Nd`) classes, generated against the Unicode
//! Character Database version the script's Python interpreter ships
//! (#448 decision: electricity matches CPython 3.11 exactly, not
//! whatever Unicode version Rust's own tables carry).
//!
//! Unicode Character Database version: {unicodedata.unidata_version}.

/// `\\w` without the trailing `_` member (added separately by the
/// translator, since `_` is not itself alphanumeric) -- `str.isalnum()`.
pub(crate) const WORD_RANGES: &[(u32, u32)] = &[
{body(word)}
];

/// `\\s` -- `str.isspace()`.
pub(crate) const SPACE_RANGES: &[(u32, u32)] = &[
{body(space)}
];

/// `\\d` -- Unicode category `Nd`.
pub(crate) const DIGIT_RANGES: &[(u32, u32)] = &[
{body(digit)}
];
"""


def main() -> int:
    word = ranges_where(lambda c: c.isalnum())
    space = ranges_where(lambda c: c.isspace())
    digit = ranges_where(lambda c: unicodedata.category(c) == "Nd")
    text = render(word, space, digit)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is stale; run without --check to regenerate", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
