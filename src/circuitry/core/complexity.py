"""Deterministic complexity scoring for prompt effects.

A prompt's *complexity* here is a mechanical estimate of how much work the model
is being asked to do — not a judgement about the task, and never a model call.
Everything in this module is a pure function of its arguments: no adapter, no
store, no config read, no clock, no randomness, no IO. The same inputs always
produce the same number, which is what makes the score usable as a routing
input (pick a bigger model for a harder prompt) and as a lint signal.

Signals
-------

Seven signals are measured, each producing a raw measurement and a *normalized*
value in ``[0, 1]``:

===================  =======================================================
``prompt_size``      Token estimate of the prompt — the rendered prompt when
                     one is supplied, the template/messages otherwise.
``state_references`` Distinct ``{{...}}`` references in the template. More
                     interpolated state means more context to reconcile.
``output_type``      ``prompt_type``: ``boolean`` is cheap, ``array``/``json``
                     demand structure.
``schema_shape``     Depth and breadth of a declared output schema.
``output_size``      Declared output limits (``maxItems``, ``maxLength``,
                     ``max_tokens``) — how much text has to come back.
``structure``        Structural position: nesting depth, loop body, whether
                     the effect was generated by a reflector.
``keywords``         Deterministic keyword matching against a weight table.
                     String matching, not a model judgement.
===================  =======================================================

Scoring
-------

Each normalized value is multiplied by its weight, and the weighted mean is
scaled onto a bounded, documented range — ``0.0`` to :data:`MAX_SCORE` (100.0).
Because the score is a weighted *mean* it is portable: changing the weights
rescales the emphasis, not the range, so band tables written against 0–100 stay
valid.

    score = MAX_SCORE * Σ(weightᵢ × normalizedᵢ) / Σ(weightᵢ)

Every term of that sum is reported. :class:`SignalScore` carries the raw
measurement, the weight applied, the normalized value, and the contribution *in
score points*, so a total can be reconstructed by summing contributions — no
re-running the scorer to find out where a surprising number came from::

    result = score(effect)
    assert abs(sum(s.contribution for s in result.signals) - result.score) < 1e-6
    print(result.explain())

Modes
-----

Scoring works with or without a rendered prompt. With one (``mode="rendered"``)
the size signal measures what is actually being sent. Without one
(``mode="static"``, the default) it measures the template and the result is
flagged ``estimated=True`` — the interpolated state is not there yet, so the
real prompt is at least as large. Static mode is what ``cof score`` and lint
use; rendered mode is what the runtime uses once a prompt is materialized.

Degradation
-----------

Nothing here raises on bad input. Unknown ``prompt_type``, a schema that is not
a mapping, a weight that is not a number, a definition that is ``None`` — each
degrades to a neutral measurement and appends a line to
:attr:`ComplexityScore.warnings`.
"""

